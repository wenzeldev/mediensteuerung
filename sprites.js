function sprite(cr, rows, x, y, colors) {
    for (const [index, color] of colors.entries()) {
        const code = String(index + 1);
        cr.setSourceRGBA(...color, 1);
        for (const [dy, row] of rows.entries()) {
            for (let dx = 0; dx < row.length; dx++) {
                if (row[dx] === code)
                    cr.rectangle(x + dx, y + dy, 1, 1);
            }
        }
        cr.fill();
    }
}

function points(cr, pixels, color, opacity = 1) {
    cr.setSourceRGBA(...color, opacity);
    for (const [x, y] of pixels)
        cr.rectangle(x, y, 1, 1);
    cr.fill();
}

