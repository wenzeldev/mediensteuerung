function rider(cr, tick) {
    const white = [1, 1, 1];
    const stride = Math.floor(tick / 2) % legs.length;
    const bob = [0, 1, 1, 0][stride];
    const x = 12 + Math.round(5 * Math.sin(tick * Math.PI / 48));
    sprite(cr, horse, x, 3 + bob, [white]);
    sprite(cr, legs[stride], x + 3, 10 + bob, [white]);
    sprite(cr, saddle, x + 8, 1 + bob, [white]);
    const swing = stride === 1 || stride === 2 ? 1 : 0;
    points(cr, [[x + 15, 5 + bob], [x + 16, 4 + bob], [x + 17, 3 + bob],
        [x + 18 + swing, 2 + bob], [x + 19 + swing, 1 + bob], [x + 20 + swing, bob],
        [x + 16, 2 + bob], [x + 18, 4 + bob]], white);
    points(cr, [0, 1, 2, 3].map(i => [54 - (tick * 2 + i * 13) % 54, 15 - i % 2]), white, 0.36);
}

export function paintSprite(cr, {style, phase, color, secondary}) {
    const tick = Math.floor(phase / (2 * Math.PI) * 96);
    if (style === 'rider') {
        rider(cr, tick);
        return;
    }

    const wave = n => Math.sin(tick / 96 * 2 * Math.PI * n);
    const bob = Math.round(wave(4));
    const drift = Math.round(10 * wave(1));
    const draw = (x, y, flip = false) => sprite(cr, flip
        ? sprites[style].map(row => [...row].reverse().join('')) : sprites[style],
    x, y, [color, secondary]);
    const accents = (pixels, opacity) => points(cr, pixels, secondary, opacity);

    switch (style) {
    case 'star': {
        const step = Math.floor(tick / 4) % 4;
        const x = 20 + [-5, 0, 5, 0][step];
        const y = [2, 0, 2, 1][step];
        draw(x, y, step >= 2);
        accents([[8 + step, 4], [9 + step, 3], [9 + step, 5], [10 + step, 4],
            [45 - step, 11], [46 - step, 10], [47 - step, 11], [46 - step, 12]]);
        break;
    }
    case 'jelly':
        draw(19 + drift, 1 + bob);
        accents([0, 1, 2, 3, 4].map(i => [4 + i * 11, 15 - (tick + i * 3) % 16]), 0.55);
        break;
    case 'moth': {
        const x = 15 + Math.round(drift / 2);
        cr.save();
        if (tick % 8 >= 4) {
            cr.translate(x + 5, 0);
            cr.scale(0.6, 1);
            draw(0, 2 + bob);
        } else {
            draw(x, 2 + bob);
        }
        cr.restore();
        accents([[44, 1], [43, 2], [43, 3], [43, 4], [44, 5], [45, 5], [46, 4], [7, 11]], 0.85);
        break;
    }
    case 'train': {
        const x = 7 + Math.round(5 * wave(2));
        draw(x, 3);
        accents([0, 1, 2, 3].map(i => [x + 19 - i * 4, 3 - (tick + i * 3) % 4]), 0.65);
        accents([0, 1, 2, 3, 4, 5, 6].map(i => [i * 8 + (96 - tick) % 8, 15]), 0.45);
        break;
    }
    case 'koi':
        draw(17 + drift, 4 + bob, Math.cos(tick / 96 * 2 * Math.PI) < 0);
        accents([0, 1, 2, 3, 4, 5].map(i => [(tick + i * 11) % 56, 1 + i * 2]), 0.5);
        break;
    case 'portal': {
        const ring = [[42,0],[43,1],[44,2],[45,3],[46,4],[46,5],[46,6],[46,7],[46,8],
            [46,9],[46,10],[45,11],[44,12],[43,13],[42,14],[41,13],[41,1]];
        cr.save();
        cr.rectangle(0, 0, 43, 16);
        cr.clip();
        draw(10 + Math.floor(tick / 3), 2 + Math.floor(tick % 8 / 4));
        cr.restore();
        accents(ring, 0.55);
        accents([ring[Math.floor(tick / 2) % ring.length]]);
        break;
    }
    case 'mushroom':
        draw(16, 2);
        accents([0, 1, 2, 3, 4].map(i => {
            const age = (Math.floor(tick / 2) + i * 5) % 24;
            return [24 + i + age, (18 - age) % 14];
        }), 0.72);
        break;
    case 'skull': {
        const x = 20 + Math.round(drift / 2);
        draw(x, 4);
        accents([[-4, 0], [-3, -1], [-2, -1], [-1, -1], [0, -1], [1, -1],
            [2, -1], [3, -1], [4, 0], [3, 1], [2, 1], [-2, 1], [-3, 1]]
            .map(([dx, y]) => [x + 6 + dx, 2 + y]));
        accents([[8, 5], [12, 11], [44, 7], [49, 10]], 0.65);
        break;
    }
    case 'astronaut':
        draw(17 + Math.round(drift / 2), 1 + bob);
        accents(Array.from({length: 14}, (_, i) => [
            30 + Math.round(drift / 2) + i, 10 + bob - Math.round(i / 3 + 2 * wave(2)),
        ]), 0.7);
        accents([[4, 3], [9, 12], [42, 3], [48, 9]], 0.55);
        break;
    case 'dragon': {
        const x = 9 + Math.round(drift / 2);
        draw(x, 1 + bob);
        accents([0, 1, 2, 3, 4].map(i => {
            const age = (tick + i * 5) % 22;
            return [x + 23 + age, 7 + bob - Math.floor(age / 4) + i % 2];
        }), 0.9);
        break;
    }
    }
}
